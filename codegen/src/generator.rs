/// The module path of the runtime's async driver, which its `async` feature
/// gates: a file that uses it needs the feature turned on.
const ASYNC_DRIVER: &str = "comline_runtime::async_connection::";

/// `comline-runtime` — the crate the generated RPC code links against. Pinned
/// by git rev (no crates.io yet); see design/runtime-repo-structure.md.
const RUNTIME_GIT: &str = "https://github.com/ComlineProject/runtime";
const RUNTIME_REV: &str = "2f71757d5f941a89a2e4c29cdffe971ee316dc35";

/// `comline_std` — std's own pre-generated bindings, referenced instead of
/// inlined when `external_std` is on. Same git-pin shape as
/// `comline-runtime` above, pointing at `comline-rust`'s own `std-extra/`
/// (see `xtask/`, which regenerates it and is what this pin must match).
const STD_GIT: &str = "https://github.com/ComlineProject/comline-rust";
pub const STD_REV: &str = "3c6df80fa2b47760fc8932d6035b22193bbc35f1";

pub fn generate_rust(req: &GenRequest) -> Result<Vec<GeneratedFile>> {
    // What this generator can't render at all is refused up front, every use
    // named, before a single file is produced.
    comline_codegen::features::refuse_unsupported("rust", req, crate::SUPPORT)?;

    let default_framing = req.default_framing.as_deref();
    // A name `framing_for` doesn't know would fall through to datagram below,
    // and the mismatch would only surface as a refused handshake. `@framing`
    // is checked by core; the package default arrives unchecked from the
    // caller, so it's checked here.
    if let Some(name) = default_framing {
        if framing_for(name).is_none() {
            return Err(eyre::eyre!(
                "unknown default framing `{name}` - expected one of {}",
                comline_core::schema::idl::annotations::value_spellings("framing")
                    .iter()
                    .map(|n| format!("`{n}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
    }

    // Only *emission* is narrowed by `external_std`; `req.schemas` stays
    // the list every reference resolves against. `stdlib::split` carries
    // that distinction, and the "declare the dependency only if std was
    // actually there" subtlety with it.
    let std = stdlib::split(req.schemas, req.external_std);
    let schemas = std.emitted.as_ref();

    // Before emitting anything: a name this generator is about to invent may
    // already mean something in the schema. `protocol Gateway` plus an
    // `error GatewayError` used to emit two types of that name and leave the
    // author with a redefinition error pointing into code they never wrote.
    // Checked for every schema first, so a collision in the last one does not
    // arrive after the earlier files are already written.
    for (namespace, units) in schemas {
        collisions::check(namespace, units, derived_names(units, req.schemas, default_framing, req.async_api))?;
    }
    // JSON-RPC protocols sharing a connection whose bare method names one
    // side couldn't tell apart.
    connections::check(req.schemas, default_framing)?;

    // What each value's validation runs, resolved against every schema in
    // the request - a validator or alias can come from one this crate
    // doesn't emit (std's, under `external_std`).
    let model = Validation::new(req.schemas);
    // Which toolchains the file is for: the target's minimum, and the newest
    // this generator's output is verified against.
    let header = format!(
        "// Generated by Comline\n// For Rust {} or later; verified up to {}.\n",
        req.lang_version,
        crate::VERSIONS.verified_up_to
    );
    let render = |namespace: &str, units: &[FrozenUnit]| {
        schema_source(
            namespace,
            units,
            req.schemas,
            default_framing,
            req.external_std,
            &model,
            req.validate_on_decode,
            req.async_api,
        )
        .map(|body| format!("{header}{body}"))
    };

    match req.mode {
        // No manifest to add `comline_std` to on the caller's behalf here
        // (unlike `lib` mode's `Cargo.toml`, below) - a file that ends up
        // referencing it gets a comment naming the dependency line to add
        // by hand.
        Mode::Code => schemas
            .iter()
            .map(|(namespace, units)| {
                let contents = render(namespace, units)?;
                let contents = if contents.contains("comline_std::") {
                    format!(
                        "// This file references `comline_std` - add it to your Cargo.toml:\n\
                         // comline_std = {{ git = \"{STD_GIT}\", rev = \"{STD_REV}\" }}\n{contents}"
                    )
                } else {
                    contents
                };
                let contents = if contents.contains("serde_big_array::") {
                    format!(
                        "// This file uses `serde_big_array` - add it to your Cargo.toml:\n\
                         // {BIG_ARRAY_DEP}\n{contents}"
                    )
                } else {
                    contents
                };
                // The async driver is behind a runtime feature, which nothing
                // in the code itself would tell a reader.
                let contents = if contents.contains(ASYNC_DRIVER) {
                    format!(
                        "// This file uses `comline_runtime`'s async driver - enable its feature in your Cargo.toml:\n\
                         // comline-runtime = {{ git = \"{RUNTIME_GIT}\", rev = \"{RUNTIME_REV}\", features = [\"async\"] }}\n{contents}"
                    )
                } else {
                    contents
                };
                // A protocol already needs the runtime, and says so by using
                // it throughout; validation alone is easy to miss.
                let contents = if contents.contains("comline_runtime::validation::")
                    && !contents.contains("use comline_runtime::")
                {
                    format!(
                        "// This file uses `comline_runtime` - add it to your Cargo.toml:\n\
                         // comline-runtime = {{ git = \"{RUNTIME_GIT}\", rev = \"{RUNTIME_REV}\" }}\n{contents}"
                    )
                } else {
                    contents
                };
                Ok(GeneratedFile { path: PathBuf::from(format!("{namespace}.rs")), contents })
            })
            .collect(),

        Mode::Lib => {
            let tree = NamespaceTree::build(schemas, &RustLayout)?;

            // Rendered before the manifest, which has to know what they use.
            let sources: HashMap<&str, String> = schemas
                .iter()
                .map(|(namespace, units)| Ok((namespace.as_str(), render(namespace, units)?)))
                .collect::<Result<_>>()?;

            // A protocol links the runtime, and so does any validation.
            let needs_runtime = sources.values().any(|s| s.contains("comline_runtime::"));
            // The async driver is behind the runtime's `async` feature.
            let needs_async = sources.values().any(|s| s.contains(ASYNC_DRIVER));

            let needs_big_array = schemas.iter().any(|(_, units)| uses_big_array(units));

            let mut files = vec![GeneratedFile {
                path: PathBuf::from("Cargo.toml"),
                contents: cargo_toml(
                    &req.package,
                    &req.lang_version,
                    needs_runtime,
                    needs_async,
                    std.needs_std_dependency,
                    needs_big_array,
                ),
            }];
            // The render closure takes every schema in the request, not just
            // the ones in this tree: a reference resolves against all of
            // them, including an external `std` this crate emits no file for.
            files.extend(tree.emit("src", &RustLayout, &|namespace, _units| {
                sources.get(namespace).cloned().unwrap_or_default()
            }));
            Ok(files)
        }
    }
}

/// What Rust decides differently about the `src/` tree
/// ([`comline_codegen::modules`] holds the rest).
///
/// Three things: the extension, a module file *beside* its directory rather
/// than inside it (2021-edition style — `src/std.rs` + `src/std/http.rs`, no
/// `mod.rs`), with the crate root the one special case (`src/lib.rs`, not
/// `src.rs`), and `pub mod` as the declaration — which, unlike TypeScript's
/// `export * as`, is the same line whether the child is a schema or a
/// grouping, since Rust resolves `foo` to `foo.rs` or `foo/` itself.
///
/// Plus the one reserved root: `lib` is the crate root.
struct RustLayout;

impl TreeLayout for RustLayout {
    fn ext(&self) -> &str {
        "rs"
    }

    /// Beside the directory, except at the crate root.
    fn group_file(&self, prefix: &str, is_root: bool) -> String {
        if is_root {
            format!("{prefix}/lib.rs")
        } else {
            format!("{prefix}.rs")
        }
    }

    fn declare_child(&self, segment: &str, _child_is_leaf: bool) -> String {
        format!("pub mod {};\n", ident(segment))
    }

    fn reserved_roots(&self) -> &[&str] {
        &["lib"]
    }

    /// `src/std.rs` has to be *either* `std`'s own generated code *or* its
    /// `pub mod` declarations, and there is nowhere to put the other.
    fn ambiguity_reason(&self, _path: &str) -> String {
        "there's no single file for that to be".to_string()
    }

    /// A schema named `lib` used to be emitted straight over `src/lib.rs`,
    /// taking the whole `pub mod` tree with it. Core refuses the name when a
    /// package is compiled; this catches a `GenRequest` built by hand, since
    /// that is a public contract.
    ///
    /// The check is on a namespace's *first* segment, so `lib/foo` is
    /// refused too — it would make `lib` a grouping node whose own file is
    /// `src/lib.rs`, clobbering the crate root exactly as a schema named
    /// `lib` did. Core's own check covers both from a real project
    /// (`reserved_in_namespace` looks at every segment); this is for a
    /// `GenRequest` built by hand.
    fn reserved_root_reason(&self, _name: &str) -> String {
        "`src/lib.rs` is the crate root, so a schema there would overwrite \
         the module tree - rename the schema"
            .to_string()
    }
}

/// `lang_version` is the toolchain the target declared (`rust#1.85.0`), so
/// the crate states the version it was generated for rather than leaving a
/// consumer to discover it by failing to build.
fn cargo_toml(
    pkg: &PackageMeta,
    lang_version: &str,
    needs_runtime: bool,
    needs_async: bool,
    needs_std_dep: bool,
    needs_big_array: bool,
) -> String {
    let mut deps = String::from("serde = { version = \"1\", features = [\"derive\"] }\n");
    if needs_big_array {
        deps.push_str(BIG_ARRAY_DEP);
        deps.push('\n');
    }
    if needs_runtime {
        let features = if needs_async { ", features = [\"async\"]" } else { "" };
        deps.push_str(&format!(
            "comline-runtime = {{ git = \"{RUNTIME_GIT}\", rev = \"{RUNTIME_REV}\"{features} }}\n"
        ));
    }
    if needs_std_dep {
        deps.push_str(&format!(
            "comline_std = {{ git = \"{STD_GIT}\", rev = \"{STD_REV}\" }}\n"
        ));
    }
    format!(
        "# Generated by Comline\n\
         [package]\n\
         name = \"{}\"\n\
         version = \"{}\"\n\
         edition = \"2024\"\n\
         rust-version = \"{lang_version}\"\n\
         # A schema namespace named `main` would otherwise be picked up as a\n\
         # binary target (`src/main.rs`) with no `fn main`. Core refuses that\n\
         # name outright now; this stays as a belt-and-braces guard for a\n\
         # `GenRequest` built by hand.\n\
         autobins = false\n\
         \n\
         [dependencies]\n\
         {deps}",
        pkg.name, pkg.version
    )
}

#[allow(clippy::too_many_arguments)]
fn schema_source(
    namespace: &str,
    units: &[FrozenUnit],
    schemas: &[(String, Vec<FrozenUnit>)],
    default_framing: Option<&str>,
    external_std: bool,
    model: &Validation,
    on_decode: ValidateOnDecode,
    async_api: bool,
) -> Result<String> {
    let has_protocol = units
        .iter()
        .any(|u| matches!(u, FrozenUnit::Protocol { .. }));
    // Which runtime API this file's protocols use: the lockstep `Client` /
    // `Server`, a `Connection`, or both.
    let on_connection = |u: &FrozenUnit| match u {
        FrozenUnit::Protocol { parameters, .. } => {
            Some(connections::on_connection(schemas, parameters, default_framing))
        }
        _ => None,
    };
    let has_lockstep = units.iter().any(|u| on_connection(u) == Some(false));
    let has_connection = units.iter().any(|u| on_connection(u) == Some(true));
    // `async`: every protocol on a connection is async, on an
    // `AsyncConnection`, and none uses the blocking connection API.
    let has_async = async_api && has_connection;
    let has_blocking_connection = has_connection && !async_api;
    let errors: HashMap<u16, String> =
        error_names(units).into_iter().map(|(ordinal, name)| (ordinal, ident(&name))).collect();
    let imports = import_paths(units, schemas, external_std);

    // Only a `derive`d type needs serde, and a schema can legitimately
    // declare none - `std/validators` declares only validators, so its
    // generated file was an unused import and nothing else, which is a
    // warning a consumer cannot do anything about. A `type` alias needs no
    // derive either; a protocol does, for its generated params structs.
    let needs_serde = units.iter().any(|u| {
        matches!(
            u,
            FrozenUnit::Struct { .. }
                | FrozenUnit::Error { .. }
                | FrozenUnit::Enum { .. }
                | FrozenUnit::Protocol { .. }
        )
    });

    let mut output = String::new();
    if needs_serde {
        output.push_str("use serde::{Deserialize, Serialize};\n");
    }
    if has_lockstep {
        output.push_str("use comline_runtime::client::Client;\n");
    }
    if has_async {
        output.push_str(
            "use comline_runtime::async_connection::{Answer, AsyncConnection, AsyncDispatch, AsyncPeer, AsyncTransport};\n",
        );
    }
    if has_blocking_connection {
        output.push_str("use comline_runtime::connection::Connection;\n");
    }
    // A blocking dispatcher records its outcome in a `Reply`; an async one
    // returns an `Answer`.
    let blocking = has_lockstep || has_blocking_connection;
    if blocking {
        output.push_str(
            "use comline_runtime::contract::{\n    \
                 Call, CallError, Dispatch, Envelope, Fault, Kind, Reply, RuntimeError, WireFormat,\n\
             };\n",
        );
    } else if has_protocol {
        output.push_str(
            "use comline_runtime::contract::{Call, CallError, Envelope, Fault, Kind, RuntimeError, WireFormat};\n",
        );
    }
    if has_blocking_connection {
        output.push_str(
            "use comline_runtime::contract::{ConnectionFraming, Peer, ProtocolNumber};\n",
        );
    } else if has_async {
        output.push_str("use comline_runtime::contract::{ConnectionFraming, ProtocolNumber};\n");
    }
    if has_lockstep {
        output.push_str("use comline_runtime::serve::Server;\n");
    }
    if blocking {
        output.push_str("use comline_runtime::transport::Transport;\n");
    }
    output.push('\n');

    if has_protocol {
        output.push_str(&format!(
            "/// Canonical digest of the frozen IR this file was generated from — the\n\
             /// two ends of a connection must agree on it, and the handshake checks.\n\
             pub const IR_HASH: u64 = {:#018x};\n\n",
            schema_ir_hash(units)
        ));
    }
    if has_connection {
        output.push_str(&format!(
            "/// Digest of every schema in the package — what a connection's handshake\n\
             /// checks, so both ends agree on each protocol's number.\n\
             pub const CONNECTION_IR_HASH: u64 = {:#018x};\n\n",
            connections::connection_ir_hash(schemas)
        ));
    }

    for unit in units {
        match unit {
            FrozenUnit::Struct { name, fields, .. } => {
                let members = validate::field_members(model, namespace, name, fields)?;
                output.push_str(&data_struct(name, fields, &imports, &members, on_decode)?);
            }
            FrozenUnit::Enum { name, variants, .. } => {
                output.push_str(&data_enum(name, variants));
            }
            FrozenUnit::Error {
                name,
                message,
                fields,
                ..
            } => {
                let members = validate::field_members(model, namespace, name, fields)?;
                output.push_str(&error_struct(
                    name, message, fields, &imports, &members, on_decode,
                )?);
            }
            FrozenUnit::TypeAlias { name, target, .. } => {
                output.push_str(&type_alias(name, target, &imports));
            }
            FrozenUnit::Constant {
                docstring,
                name,
                ty,
                value,
                ..
            } => {
                output.push_str(&constant(docstring.as_deref(), name, ty, value.as_ref()));
            }
            FrozenUnit::Protocol {
                name,
                functions,
                parameters,
                ..
            } => {
                output.push_str(&protocol(
                    name,
                    functions,
                    parameters,
                    schemas,
                    default_framing,
                    &errors,
                    &imports,
                    namespace,
                    model,
                    on_decode,
                    async_api,
                )?);
            }
            _ => {}
        }
    }

    Ok(output)
}

// ── data types ─────────────────────────────────────────────────────────────

fn field_lines(fields: &[FrozenUnit], imports: &HashMap<String, String>) -> String {
    let mut s = String::new();
    for field in fields {
        if let FrozenUnit::Field {
            name,
            ty,
            optional,
            ..
        } = field
        {
            // serde's own derive covers arrays up to 32; past that the field
            // goes through `serde_big_array`. `refuse_unsupported` has already
            // refused the cases this attribute can't reach.
            if !*optional && is_big_array(ty) {
                s.push_str("    #[serde(with = \"serde_big_array::BigArray\")]\n");
            }
            let rust = rust_type(ty, imports);
            let rust = if *optional {
                format!("Option<{rust}>")
            } else {
                rust
            };
            s.push_str(&serde_rename(name, "    "));
            s.push_str(&format!("    pub {}: {rust},\n", ident(name)));
        }
    }
    s
}

fn data_struct(
    name: &str,
    fields: &[FrozenUnit],
    imports: &HashMap<String, String>,
    members: &[Member],
    on_decode: ValidateOnDecode,
) -> Result<String> {
    let lines = field_lines(fields, imports);
    Ok(format!(
        "#[derive(Debug, Clone, Serialize, Deserialize)]\n{}pub struct {} {{\n{lines}}}\n\n{}{}",
        validate::try_from_attribute(&ident(name), on_decode, members),
        ident(name),
        validate::validate_impl(&ident(name), "", members)?,
        validate::decode_shadow(&ident(name), on_decode, members, &lines),
    ))
}

/// `type NAME = TARGET;` - transparent like Rust's own `type` (not a
/// newtype): `rust_type` already maps any type to a real Rust type
/// expression, named or primitive, so this is the same mapping every field
/// already goes through, just at the top level of the file instead of
/// inside a struct.
fn type_alias(name: &str, target: &TypeRef, imports: &HashMap<String, String>) -> String {
    format!("pub type {} = {};\n\n", ident(name), rust_type(target, imports))
}

/// `const MAX_RETRIES: u8 = 5` -> `pub const MAX_RETRIES: u8 = 5;`.
///
/// Declarations used to vanish here: a schema of nothing but constants
/// generated an empty file in both targets. The type is the declared one
/// the IR carries, next to the literal - never inferred from the literal,
/// which once emitted a `u8` constant as `u64`.
///
/// Rendered from the primitive directly rather than through
/// [`rust_type`]: a `const` is not a struct field, and the two differ. A
/// text constant is `&str` - `String` cannot be built in a `const`, and the
/// explicit `'static` a `const` would accept is what clippy's
/// `redundant_static_lifetimes` fires on, which is the same generated-code
/// noise the conditional serde import above exists to avoid.
fn constant(
    docstring: Option<&str>,
    name: &str,
    ty: &TypeRef,
    value: Option<&Literal>,
) -> String {
    // Validation refuses a constant that isn't a primitive with a literal
    // value, so neither early return is reachable from a real build.
    // Emitting nothing rather than guessing keeps it that way.
    let Some(primitive) = ty.as_primitive() else {
        return String::new();
    };
    let (ty, value) = match (primitive, value) {
        (PrimitiveType::String, Some(Literal::String(text))) => {
            ("&str".to_string(), format!("{text:?}"))
        }
        // A float constant written as an integer (`= 2`) needs a decimal
        // point to be a float in Rust.
        (p, Some(Literal::Integer(i))) if p.is_float() => {
            (primitive_type(p).to_string(), format!("{i}.0"))
        }
        (p, Some(literal @ (Literal::Integer(_) | Literal::Bool(_)))) => {
            (primitive_type(p).to_string(), literal.to_string())
        }
        _ => return String::new(),
    };

    let mut s = String::new();
    for line in docstring.unwrap_or_default().lines() {
        s.push_str(&format!("/// {line}\n"));
    }
    s.push_str(&format!("pub const {name}: {ty} = {value};\n\n"));
    s
}

/// An `error`'s payload struct, plus the `Display` that renders the `message`
/// the schema requires. Without it the sentence the author wrote was dropped
/// on the floor and a raised error printed as its `Debug` shape at best.
///
/// And `core::error::Error`, stable since Rust 1.81, below this generator's
/// floor.
fn error_struct(
    name: &str,
    message: &str,
    fields: &[FrozenUnit],
    imports: &HashMap<String, String>,
    members: &[Member],
    on_decode: ValidateOnDecode,
) -> Result<String> {
    let field_names: Vec<String> = fields
        .iter()
        .filter_map(|f| match f {
            FrozenUnit::Field { name, .. } => Some(name.clone()),
            _ => None,
        })
        .collect();
    let lines = field_lines(fields, imports);
    let name = &ident(name);
    Ok(format!(
        "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n{}pub struct {name} {{\n{lines}}}\n\n\
         impl core::fmt::Display for {name} {{\n    \
             fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {{\n        \
                 {}\n    \
             }}\n\
         }}\n\n\
         impl core::error::Error for {name} {{}}\n\n{}{}",
        validate::try_from_attribute(name, on_decode, members),
        crate::message::render(message, &field_names).write_call("f"),
        validate::validate_impl(name, "", members)?,
        validate::decode_shadow(name, on_decode, members, &lines),
    ))
}

fn data_enum(name: &str, variants: &[FrozenUnit]) -> String {
    let mut s = format!(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]\npub enum {} {{\n",
        ident(name)
    );
    for variant in variants {
        if let FrozenUnit::EnumVariant(variant_name, _) = variant {
            s.push_str(&serde_rename(variant_name, "    "));
            s.push_str(&format!("    {},\n", ident(variant_name)));
        }
    }
    s.push_str("}\n\n");
    s
}

/// Every name this generator will invent for `units`, each described the way a
/// person reading a build failure needs it.
///
/// This is the half of collision checking that cannot live in
/// `comline-codegen`: what gets derived is a fact about *Rust* output, not
/// about the schema. Keep it in step with the emitters below — a name added
/// there and not here is a collision that still reaches the compiler.
fn derived_names(
    units: &[FrozenUnit],
    schemas: &[(String, Vec<FrozenUnit>)],
    default_framing: Option<&str>,
    async_api: bool,
) -> Vec<Derived> {
    let mut derived = Vec::new();
    let mut any_protocol = false;
    let mut any_connection = false;

    for unit in units {
        let FrozenUnit::Protocol {
            name: proto,
            functions,
            parameters,
            ..
        } = unit
        else {
            continue;
        };
        any_protocol = true;
        let connection = connections::on_connection(schemas, parameters, default_framing);
        any_connection |= connection;

        derived.push(Derived::new(
            format!("{proto}Error"),
            format!("protocol `{proto}`'s error union"),
        ));
        // An async protocol's dispatcher and sender say so in their names.
        let flavour = if connection && async_api { "Async" } else { "" };
        derived.push(Derived::new(
            format!("{proto}{flavour}Dispatcher"),
            format!("protocol `{proto}`'s dispatcher"),
        ));
        if connection {
            derived.push(Derived::new(
                format!("{proto}{flavour}Sender"),
                format!("protocol `{proto}`'s sender"),
            ));
        } else {
            derived.push(Derived::new(
                format!("{proto}Client"),
                format!("protocol `{proto}`'s client"),
            ));
        }
        derived.push(Derived::new(
            format!("{}_CALLS", screaming_snake(proto)),
            format!("protocol `{proto}`'s call table"),
        ));

        for function in functions {
            let FrozenUnit::Function {
                name,
                arguments,
                _return,
                ..
            } = function
            else {
                continue;
            };
            let from = format!("protocol `{proto}`, function `{name}`");
            // A one-way function gets no error type (nowhere to deliver one).
            if _return.is_some() {
                derived.push(Derived::new(
                    format!("{proto}{}Error", pascal(name)),
                    format!("{from}'s error type"),
                ));
            }
            if !arguments.is_empty() {
                derived.push(Derived::new(
                    format!("{proto}{}Params", pascal(name)),
                    format!("{from}'s params struct"),
                ));
            }
        }
    }

    if any_protocol {
        derived.push(Derived::new("IR_HASH", "the schema's IR hash constant"));
    }
    if any_connection {
        derived.push(Derived::new("CONNECTION_IR_HASH", "the package's connection hash constant"));
    }
    derived
}

/// One generated error type: the per-function `<Proto><Fn>Error`, or the
/// protocol-wide `<Proto>Error` union. `throws` is `(ordinal, error name)` in
/// the order the variants should appear.
///
/// With nothing to put in it this emits a **type alias to the never type**
/// rather than `pub enum Foo {}`. It names the same thing — a function that
/// declares no `!` cannot raise anything, and the wire has no ordinal for a
/// failure the schema never described — but it names it the way every Rust
/// reader already knows, and `Infallible` brings `Display`, `Copy`, `Eq` and
/// `Hash`, where an empty enum brings nothing at all. The name survives, so
/// hand-written code and docs that spell it keep working, and the
/// dispatcher's `match never {}` arm stays valid because `Infallible` is
/// uninhabited too.
///
/// A `Display` impl only makes sense on the real enum: the alias is a foreign
/// type, so implementing a trait for it here would not even compile.
fn error_type(name: &str, throws: &[(u16, String)]) -> String {
    if throws.is_empty() {
        return format!("pub type {name} = ::core::convert::Infallible;\n\n");
    }

    let mut s = format!("#[derive(Debug, Clone, PartialEq)]\npub enum {name} {{\n");
    for (_, err) in throws {
        s.push_str(&format!("    {err}({err}),\n"));
    }
    s.push_str("}\n\n");

    s.push_str(&format!(
        "impl core::fmt::Display for {name} {{\n    \
             fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {{\n        \
                 match self {{\n"
    ));
    for (_, err) in throws {
        s.push_str(&format!("            {name}::{err}(e) => e.fmt(f),\n"));
    }
    s.push_str("        }\n    }\n}\n\n");
    s.push_str(&format!("impl core::error::Error for {name} {{}}\n\n"));
    s
}

// ── protocol ───────────────────────────────────────────────────────────────

struct Arg {
    /// The schema's name: the params struct's field on the wire.
    name: String,
    /// The same as a Rust identifier ([`ident`]).
    ident: String,
    /// The type in the provider trait / client signatures (`&str`, `u32`, `Msg`).
    sig_ty: String,
    /// The type in the params struct — `&'a str` where `sig_ty` is `&str`,
    /// otherwise identical. The params struct decodes borrowed from the wire.
    field_ty: String,
}

impl Arg {
    fn borrows(&self) -> bool {
        self.field_ty.contains("'a")
    }
}

struct FnInfo {
    /// What a call names it on the wire, and the call table holds: the
    /// schema's name, or under JSON-RPC's qualified method names
    /// `ns.Proto/name`.
    method: String,
    /// The same as a Rust identifier ([`ident`]).
    ident: String,
    params_ty: Option<String>,
    /// Whether the params struct needs a `<'a>` (any `&str` arg).
    params_borrows: bool,
    args: Vec<Arg>,
    ret: String,
    err_ty: String,
    /// `(ordinal, error struct type)` for each `!` on this function.
    throws: Vec<(u16, String)>,
    /// `_return: None` — fire-and-forget: `Client::notify`, the dispatcher
    /// writes no envelope, the trait method returns `()` with no error. An
    /// explicit `-> ()` (`TypeRef::Unit`) is *not* this — it's a normal
    /// request/response with an empty ack (§4.4).
    one_way: bool,
    /// `@timeout_ms = N` on the function — the client method calls
    /// `Client::call_with_timeout` with `Duration::from_millis(N)`.
    timeout_ms: Option<u64>,
}

/// The `Framing` a protocol's generated `connect` / `serve` helpers wire up.
struct FramingChoice {
    /// Path to the framing type, e.g. `comline_runtime::framing::JsonRpcFraming`.
    ty: &'static str,
    /// `true` for anything but the datagram default — those helpers pass the
    /// framing explicitly (`Client::connect_with_framing` / `Server::with_framing`)
    /// and the `Client` alias carries it as its third type parameter.
    explicit: bool,
}

/// The datagram default — the generated helpers use `Client::connect` /
/// `Server::new` and the `Client` alias keeps its two type parameters.
const DATAGRAM_FRAMING: FramingChoice = FramingChoice {
    ty: "comline_runtime::contract::DatagramFraming",
    explicit: false,
};

/// Map one framing name to a choice. `None` for a name core does not
/// recognise (the caller falls through to the next level).
///
/// The accepted spellings and their aliases come from core, not from a
/// copy kept here - this generator, the TypeScript one and the playground
/// each used to maintain their own, and they had drifted (the
/// playground's was missing `json-rpc`, so a protocol this generator emits
/// as JSON-RPC rendered as datagram there).
fn framing_for(name: &str) -> Option<FramingChoice> {
    match comline_core::schema::idl::annotations::canonical_value("framing", name)? {
        "jsonrpc" => Some(FramingChoice {
            ty: "comline_runtime::framing::JsonRpcFraming",
            explicit: true,
        }),
        "datagram" => Some(DATAGRAM_FRAMING),
        // A protocol on it runs on a `Connection`, which names its framing
        // itself; this only says the name is known.
        comline_core::schema::idl::annotations::FRAMING_DATAGRAM2 => Some(FramingChoice {
            ty: "comline_runtime::contract::Datagram2Framing",
            explicit: false,
        }),
        _ => None,
    }
}

/// Resolve a protocol's framing, most specific first: its own `@framing`
/// annotation, then the package `default_framing` (`comline.toml`), then the
/// datagram default. An unrecognised name at either level falls through.
/// The runtime's `none` handshake, by path (only a `none` protocol uses it).
const NO_HANDSHAKE: &str = "comline_runtime::handshake::NoHandshake";

/// Doc lines naming what an `@unverified` protocol gives up, and why, for
/// its dispatcher and client. Empty for a protocol that gives nothing up.
fn unverified_doc(parameters: &[FrozenUnit]) -> Vec<String> {
    let set = unverified::frozen_set(parameters);
    if set.is_empty() {
        return vec![];
    }
    let mut doc = vec![format!(
        "/// **Unverified:** gives up {} ({}).",
        unverified::describe(set),
        unverified::cause(parameters)
    )];
    if let Some(reason) = unverified::reason(parameters) {
        doc.push(format!("/// Reason given: {reason}"));
    }
    doc
}

/// `@handshake = "none"` (or the package default, which core has already
/// written here).
fn no_handshake_of(parameters: &[FrozenUnit]) -> bool {
    annotation(parameters, "handshake").as_deref() == Some(HANDSHAKE_NONE)
}

fn framing_choice(parameters: &[FrozenUnit], default_framing: Option<&str>) -> FramingChoice {
    connections::framing(parameters, default_framing)
        .and_then(|f| framing_for(f.name))
        .unwrap_or(DATAGRAM_FRAMING)
}

#[allow(clippy::too_many_arguments)]
fn protocol(
    proto: &str,
    functions: &[FrozenUnit],
    parameters: &[FrozenUnit],
    schemas: &[(String, Vec<FrozenUnit>)],
    default_framing: Option<&str>,
    errors: &HashMap<u16, String>,
    imports: &HashMap<String, String>,
    namespace: &str,
    model: &Validation,
    on_decode: ValidateOnDecode,
    async_api: bool,
) -> Result<String> {
    let framing = framing_choice(parameters, default_framing);
    // On a connection: handlers take the peer, the dispatcher is provided
    // on a `Connection`, and a sender calls through any `Peer`.
    let connection = connections::on_connection(schemas, parameters, default_framing);
    // `async`: an async trait, an `AsyncDispatcher` provided on an
    // `AsyncConnection`, and an `AsyncSender` calling through any
    // `AsyncPeer`. Only a connection protocol has an async form.
    let asynchronous = connection && async_api;
    // How the dispatcher's doc says to open the connection it's provided on.
    let open = match (framing.explicit, no_handshake_of(parameters), asynchronous) {
        (_, true, false) => "`Connection::accept_with` and `NoHandshake` (`@handshake = \"none\"`)".to_string(),
        (_, true, true) => "`AsyncConnection::new_unverified` (`@handshake = \"none\"`)".to_string(),
        (false, false, false) => "`Connection::accept(transport, format, CONNECTION_IR_HASH)`".to_string(),
        (false, false, true) => "`AsyncConnection::accept(transport, format, CONNECTION_IR_HASH)`".to_string(),
        (true, false, false) => format!(
            "`Connection::accept_with(transport, format, {}, &mut ComlineHandshake, CONNECTION_IR_HASH)`",
            framing.ty
        ),
        (true, false, true) => {
            format!("`AsyncConnection::handshake(transport, format, {}, CONNECTION_IR_HASH)`", framing.ty)
        }
    };
    // JSON-RPC names a call by its method: bare, or qualified by protocol.
    let method_names = connections::framing(parameters, default_framing)
        .filter(|f| f.name == FRAMING_JSONRPC)
        .map(|f| f.method_names)
        .unwrap_or_default();
    let number = if connection {
        connections::protocol_number(schemas, namespace, proto).ok_or_else(|| {
            eyre::eyre!("protocol `{proto}` has no number: more than 65536 protocols in the package")
        })?
    } else {
        0
    };
    let fns: Vec<FnInfo> = functions
        .iter()
        .filter_map(|f| match f {
            FrozenUnit::Function {
                name,
                parameters,
                arguments,
                _return,
                throws,
                ..
            } => Some(FnInfo {
                method: connections::method_name(namespace, proto, name, method_names),
                ..fn_info(proto, name, parameters, arguments, _return, throws, errors, imports)
            }),
            _ => None,
        })
        .collect();
    // What each function's arguments check, in `fns` order. An argument
    // carries checks only through a `type` alias.
    let param_members: Vec<Vec<Member>> = functions
        .iter()
        .filter_map(|f| match f {
            FrozenUnit::Function { name, arguments, .. } => Some(validate::argument_members(
                model,
                namespace,
                &format!("{proto}.{name}"),
                arguments,
            )),
            _ => None,
        })
        .collect::<Result<_>>()?;

    let mut s = String::new();

    // 1. params struct per function that takes arguments
    for (f, members) in fns.iter().zip(&param_members) {
        if let Some(ty) = &f.params_ty {
            let lt = if f.params_borrows { "<'a>" } else { "" };
            s.push_str(&format!(
                "#[derive(Debug, Clone, Serialize, Deserialize)]\npub struct {ty}{lt} {{\n"
            ));
            for arg in &f.args {
                if arg.borrows() {
                    s.push_str("    #[serde(borrow)]\n");
                }
                s.push_str(&serde_rename(&arg.name, "    "));
                s.push_str(&format!("    pub {}: {},\n", arg.ident, arg.field_ty));
            }
            s.push_str("}\n\n");
            s.push_str(&validate::validate_impl(ty, lt, members)?);
        }
    }

    // 2. one schema-only error type per request/response function. One-way
    //    functions have no error channel at all.
    for f in &fns {
        if f.one_way {
            continue;
        }
        s.push_str(&error_type(&f.err_ty, &f.throws));
    }

    // 2b. per-protocol union of every `!`, additive, for one broad handler
    let mut union: Vec<(u16, String)> = fns.iter().flat_map(|f| f.throws.clone()).collect();
    union.sort_by_key(|(ord, _)| *ord);
    union.dedup_by_key(|(ord, _)| *ord);
    let union_ty = format!("{proto}Error");
    s.push_str(&error_type(&union_ty, &union));
    for f in &fns {
        if f.throws.is_empty() {
            continue;
        }
        s.push_str(&format!(
            "impl From<{0}> for {union_ty} {{\n    fn from(e: {0}) -> Self {{\n        match e {{\n",
            f.err_ty
        ));
        for (_, err) in &f.throws {
            s.push_str(&format!(
                "            {}::{err}(x) => {union_ty}::{err}(x),\n",
                f.err_ty
            ));
        }
        s.push_str("        }\n    }\n}\n\n");
    }

    // 3. provider trait + the call table
    // The trait is the one place the bare name is an identifier; every
    // other item prefixes it (`{proto}Dispatcher`), which no keyword is.
    let proto_trait = ident(proto);
    if asynchronous {
        // Its handlers run inside the connection's future, which any
        // executor may move between threads.
        s.push_str(&format!("pub trait {proto_trait}: Send + Sync + 'static {{\n"));
    } else {
        s.push_str(&format!("pub trait {proto_trait} {{\n"));
    }
    // On a connection, every handler is given the peer that called it, to
    // call it back.
    let peer_arg = match (connection, asynchronous) {
        (true, true) => ", peer: &impl AsyncPeer",
        (true, false) => ", peer: &mut impl Peer",
        _ => "",
    };
    for f in &fns {
        let args = format!("{peer_arg}{}", sig_args(&f.args));
        if asynchronous {
            // Written out rather than `async fn` so the future is `Send`;
            // an implementation can still be an `async fn`.
            let output = if f.one_way {
                "()".to_string()
            } else {
                format!("Result<{}, Fault<{}>>", f.ret, f.err_ty)
            };
            s.push_str(&format!(
                "    fn {}(&self{args}) -> impl ::core::future::Future<Output = {output}> + Send;\n",
                f.ident
            ));
        } else if f.one_way {
            s.push_str(&format!("    fn {}(&self{args});\n", f.ident));
        } else {
            // `Fault<E>` rather than a bare `E`: an implementation can fail
            // in ways its schema never described, and before this it could
            // only panic. `E` may be uninhabited while `Fault<E>` is not.
            s.push_str(&format!(
                "    fn {}(&self{args}) -> Result<{}, Fault<{}>>;\n",
                f.ident, f.ret, f.err_ty
            ));
        }
    }
    s.push_str("}\n\n");

    let calls_const = format!("{}_CALLS", screaming_snake(proto));
    s.push_str(&format!(
        "pub const {calls_const}: &[&str] = &[{}];\n\n",
        fns.iter()
            .map(|f| format!("\"{}\"", f.method))
            .collect::<Vec<_>>()
            .join(", ")
    ));

    // `@handshake = "none"` (or the package default, which core has already
    // written here): connect and serve run the runtime's `NoHandshake`.
    let no_handshake = no_handshake_of(parameters);
    let unverified_doc = unverified_doc(parameters);

    // 4. dispatcher — implements the runtime `Dispatch` trait, or for an
    //    async protocol, `AsyncDispatch`
    if asynchronous {
        s.push_str(&async_dispatcher(proto, &proto_trait, &fns, &param_members, &calls_const, number, &open, &unverified_doc, on_decode));
        s.push_str(&async_sender(proto, &fns, number, &unverified_doc));
        return Ok(s);
    }
    let mut l: Vec<String> = Vec::new();
    l.extend(unverified_doc.iter().cloned());
    l.push(format!("pub struct {proto}Dispatcher<S>(pub S);"));
    l.push(String::new());
    // `reply` is only touched by request/response arms; a protocol that is
    // entirely one-way never records anything.
    let reply_param = if fns.iter().all(|f| f.one_way) {
        "_reply"
    } else {
        "reply"
    };
    l.push(format!(
        "impl<S: {proto_trait}> Dispatch for {proto}Dispatcher<S> {{"
    ));
    l.push("    fn calls(&self) -> &'static [&'static str] {".into());
    l.push(format!("        {calls_const}"));
    l.push("    }".into());
    l.push(String::new());
    if connection {
        // Its handlers take the peer, which only a connection has.
        l.push("    /// Only served on a connection, whose handlers are given the peer:".into());
        l.push("    /// anywhere else the caller hears a fault.".into());
        l.push("    fn dispatch<W: WireFormat>(".into());
        l.push("        &self,".into());
        l.push("        _call: Kind,".into());
        l.push("        _params: &[u8],".into());
        l.push("        _fmt: &W,".into());
        l.push("        reply: &mut Reply,".into());
        l.push("    ) -> Result<(), RuntimeError> {".into());
        l.push("        reply.fault();".into());
        l.push("        Ok(())".into());
        l.push("    }".into());
        l.push(String::new());
        l.push("    fn dispatch_with<P: Peer>(".into());
        l.push("        &self,".into());
        l.push("        call: Kind,".into());
        l.push("        params: &[u8],".into());
        l.push(format!("        {reply_param}: &mut Reply,"));
        l.push("        peer: &mut P,".into());
        l.push("    ) -> Result<(), RuntimeError> {".into());
        l.extend(dispatch_arms(&fns, &param_members, &calls_const, "peer.format()", "peer", on_decode, false));
    } else {
        l.push("    fn dispatch<W: WireFormat>(".into());
        l.push("        &self,".into());
        l.push("        call: Kind,".into());
        l.push("        params: &[u8],".into());
        l.push("        fmt: &W,".into());
        l.push(format!("        {reply_param}: &mut Reply,"));
        l.push("    ) -> Result<(), RuntimeError> {".into());
        l.extend(dispatch_arms(&fns, &param_members, &calls_const, "fmt", "", on_decode, false));
    }
    l.push("    }".into());
    l.push("}".into());
    l.push(String::new());
    l.push(format!("impl<S: {proto_trait}> {proto}Dispatcher<S> {{"));
    if connection {
        l.push("    /// This protocol's number on a connection.".into());
        l.push(format!("    pub const PROTOCOL: ProtocolNumber = {number};"));
        l.push(String::new());
        l.push("    /// Provide this protocol on `conn`: the peer's calls to it come here.".into());
        l.push(format!("    /// Open `conn` with {open}."));
        l.push("    pub fn provide_on<T: Transport, W: WireFormat, F: ConnectionFraming>(".into());
        l.push("        self,".into());
        l.push("        conn: &mut Connection<T, W, F>,".into());
        l.push("    ) where".into());
        l.push("        S: 'static,".into());
        l.push("    {".into());
        l.push("        conn.provide(Self::PROTOCOL, self)".into());
        l.push("    }".into());
    } else {
        if no_handshake {
            l.push("    /// Serve this protocol over `transport`. No handshake runs".into());
            l.push("    /// (`@handshake = \"none\"`): nothing checks the peer's schema or encoding.".into());
        } else {
            l.push("    /// Serve this protocol over `transport`, running the connection".into());
            l.push("    /// handshake (`IR_HASH` + `format`'s and the framing's names) against".into());
            l.push("    /// the peer first.".into());
        }
        l.push(
            "    pub fn serve<T: Transport, W: WireFormat>(self, transport: &mut T, format: W)".into(),
        );
        l.push("    -> Result<(), RuntimeError> {".into());
        let server = if framing.explicit {
            l.push(format!("        let framing = {};", framing.ty));
            "Server::with_framing(self, format, framing)"
        } else {
            "Server::new(self, format)"
        };
        if no_handshake {
            l.push(format!("        {server}.serve_with(transport, &mut {NO_HANDSHAKE}, IR_HASH)"));
        } else {
            l.push(format!("        {server}.serve(transport, IR_HASH)"));
        }
        l.push("    }".into());
    }
    l.push("}".into());
    l.push(String::new());
    l.push(String::new());
    s.push_str(&l.join("\n"));

    // 5. consumer stub — wraps a `Client`, or on a connection, a `Peer`
    let mut l: Vec<String> = Vec::new();
    l.extend(unverified_doc.iter().cloned());
    // A connection's call takes the protocol number first.
    let protocol_arg = if connection { "Self::PROTOCOL, " } else { "" };
    if connection {
        l.push(format!(
            "/// Calls protocol `{proto}` on the other end of a connection: the peer a"
        ));
        l.push("/// `Connection` reaches, or the one a handler was given.".into());
        l.push(format!("pub struct {proto}Sender<'p, P: Peer>(pub &'p mut P);"));
        l.push(String::new());
        l.push(format!("impl<'p, P: Peer> {proto}Sender<'p, P> {{"));
        l.push("    /// This protocol's number on a connection.".into());
        l.push(format!("    pub const PROTOCOL: ProtocolNumber = {number};"));
        l.push(String::new());
        l.push("    pub fn new(peer: &'p mut P) -> Self {".into());
        l.push("        Self(peer)".into());
        l.push("    }".into());
    } else {
        let client_ty = if framing.explicit {
            format!("Client<T, W, {}>", framing.ty)
        } else {
            "Client<T, W>".to_string()
        };
        l.push(format!("pub struct {proto}Client<T, W>(pub {client_ty});"));
        l.push(String::new());
        l.push(format!(
            "impl<T: Transport, W: WireFormat> {proto}Client<T, W> {{"
        ));
        l.push(format!("    pub fn new(client: {client_ty}) -> Self {{"));
        l.push("        Self(client)".into());
        l.push("    }".into());
        l.push(String::new());
        if no_handshake {
            l.push("    /// Bind to the provider. No handshake runs (`@handshake = \"none\"`).".into());
        } else {
            l.push("    /// Bind + run the connection handshake against the provider.".into());
        }
        l.push("    pub fn connect(transport: T, format: W) -> Result<Self, RuntimeError> {".into());
        if no_handshake {
            let framing_expr = if framing.explicit {
                l.push(format!("        let framing = {};", framing.ty));
                "framing"
            } else {
                DATAGRAM_FRAMING.ty
            };
            l.push(format!(
                "        Ok(Self(Client::connect_with(transport, format, {framing_expr}, &mut {NO_HANDSHAKE}, IR_HASH)?))"
            ));
        } else if framing.explicit {
            l.push(format!("        let framing = {};", framing.ty));
            l.push(
                "        Ok(Self(Client::connect_with_framing(transport, format, framing, IR_HASH)?))"
                    .into(),
            );
        } else {
            l.push("        Ok(Self(Client::connect(transport, format, IR_HASH)?))".into());
        }
        l.push("    }".into());
    }
    for (i, f) in fns.iter().enumerate() {
        let args = sig_args(&f.args);
        let param_expr = match &f.params_ty {
            Some(ty) => {
                let init = f
                    .args
                    .iter()
                    .map(|a| a.ident.clone())
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("&{ty} {{ {init} }}")
            }
            None => "&()".to_string(),
        };
        // Both addresses — the framing picks (ordinal for datagram, name for
        // a name-oriented framing like JSON-RPC).
        let addr = format!("Call::new({i}, \"{}\")", f.method);
        l.push(String::new());
        if f.one_way {
            // Fire-and-forget: no reply, so no `CallError<E>`.
            l.push(format!(
                "    pub fn {}(&mut self{args}) -> Result<(), RuntimeError> {{",
                f.ident
            ));
            l.push(format!("        self.0.notify({protocol_arg}{addr}, {param_expr})"));
            l.push("    }".into());
            continue;
        }
        l.push(format!(
            "    pub fn {}(&mut self{args}) -> Result<{}, CallError<{}>> {{",
            f.ident, f.ret, f.err_ty
        ));
        let call = match f.timeout_ms {
            Some(ms) => format!(
                "self.0.call_with_timeout({protocol_arg}{addr}, {param_expr}, core::time::Duration::from_millis({ms}))"
            ),
            None => format!("self.0.call({protocol_arg}{addr}, {param_expr})"),
        };
        l.push(format!("        let (reply, fmt) = {call}?;"));
        l.push("        match reply {".into());
        l.push(
            "            Envelope::Ok(payload) => fmt.decode(payload).map_err(CallError::Runtime),"
                .into(),
        );
        for (ord, err) in &f.throws {
            l.push(format!(
                "            Envelope::Err {{ id: {ord}u16, body }} => {{"
            ));
            l.push(format!("                let e: {err} = fmt.decode(body)?;"));
            l.push(format!(
                "                Err(CallError::App({}::{err}(e)))",
                f.err_ty
            ));
            l.push("            }".into());
        }
        l.push(
            "            Envelope::Err { id, .. } => Err(CallError::Runtime(RuntimeError::Remote { id })),"
                .into(),
        );
        l.push(
            "            Envelope::Fault => Err(CallError::Runtime(RuntimeError::Provider)),"
                .into(),
        );
        l.push("        }".into());
        l.push("    }".into());
    }
    l.push("}".into());
    l.push(String::new());
    l.push(String::new());
    s.push_str(&l.join("\n"));

    Ok(s)
}

/// An async protocol's dispatcher: `<Proto>AsyncDispatcher`, implementing
/// the runtime's `AsyncDispatch`, provided on an `AsyncConnection`.
#[allow(clippy::too_many_arguments)]
fn async_dispatcher(
    proto: &str,
    proto_trait: &str,
    fns: &[FnInfo],
    param_members: &[Vec<Member>],
    calls_const: &str,
    number: u16,
    open: &str,
    unverified_doc: &[String],
    on_decode: ValidateOnDecode,
) -> String {
    let mut l: Vec<String> = unverified_doc.to_vec();
    l.push(format!("pub struct {proto}AsyncDispatcher<S>(pub S);"));
    l.push(String::new());
    l.push(format!("impl<S: {proto_trait}> AsyncDispatch for {proto}AsyncDispatcher<S> {{"));
    l.push("    fn calls(&self) -> &'static [&'static str] {".into());
    l.push(format!("        {calls_const}"));
    l.push("    }".into());
    l.push(String::new());
    l.push("    async fn dispatch<'a, P: AsyncPeer>(".into());
    l.push("        &'a self,".into());
    l.push("        call: Kind,".into());
    l.push("        params: &'a [u8],".into());
    l.push("        peer: &'a P,".into());
    l.push("    ) -> Result<Answer, RuntimeError> {".into());
    l.extend(dispatch_arms(fns, param_members, calls_const, "peer.format()", "peer", on_decode, true));
    l.push("    }".into());
    l.push("}".into());
    l.push(String::new());
    l.push(format!("impl<S: {proto_trait}> {proto}AsyncDispatcher<S> {{"));
    l.push("    /// This protocol's number on a connection.".into());
    l.push(format!("    pub const PROTOCOL: ProtocolNumber = {number};"));
    l.push(String::new());
    l.push("    /// Provide this protocol on `conn`: the peer's calls to it come here.".into());
    l.push(format!("    /// Open `conn` with {open}."));
    l.push("    pub fn provide_on<T, W, F>(self, conn: &mut AsyncConnection<T, W, F>)".into());
    l.push("    where".into());
    l.push("        T: AsyncTransport,".into());
    l.push("        W: WireFormat + Send + Sync + 'static,".into());
    l.push("        F: ConnectionFraming + Send + Sync + 'static,".into());
    l.push("    {".into());
    l.push("        conn.provide(Self::PROTOCOL, self)".into());
    l.push("    }".into());
    l.push("}".into());
    l.push(String::new());
    l.push(String::new());
    l.join("\n")
}

/// An async protocol's sender: `<Proto>AsyncSender`, calling through any
/// `AsyncPeer` - an `AsyncConnection`'s handle, or the peer a handler was
/// given.
fn async_sender(proto: &str, fns: &[FnInfo], number: u16, unverified_doc: &[String]) -> String {
    let mut l: Vec<String> = unverified_doc.to_vec();
    l.push(format!("/// Calls protocol `{proto}` on the other end of a connection: the peer an"));
    l.push("/// `AsyncConnection`'s handle reaches, or the one a handler was given.".into());
    l.push(format!("pub struct {proto}AsyncSender<'p, P: AsyncPeer>(pub &'p P);"));
    l.push(String::new());
    l.push(format!("impl<'p, P: AsyncPeer> {proto}AsyncSender<'p, P> {{"));
    l.push("    /// This protocol's number on a connection.".into());
    l.push(format!("    pub const PROTOCOL: ProtocolNumber = {number};"));
    l.push(String::new());
    l.push("    pub fn new(peer: &'p P) -> Self {".into());
    l.push("        Self(peer)".into());
    l.push("    }".into());
    for (i, f) in fns.iter().enumerate() {
        let args = sig_args(&f.args);
        let param_expr = match &f.params_ty {
            Some(ty) => {
                let init = f.args.iter().map(|a| a.ident.clone()).collect::<Vec<_>>().join(", ");
                format!("&{ty} {{ {init} }}")
            }
            None => "&()".to_string(),
        };
        let addr = format!("Call::new({i}, \"{}\")", f.method);
        l.push(String::new());
        if f.one_way {
            // Sent when called: nothing to await.
            l.push(format!("    pub fn {}(&self{args}) -> Result<(), RuntimeError> {{", f.ident));
            l.push(format!("        self.0.notify(Self::PROTOCOL, {addr}, {param_expr})"));
            l.push("    }".into());
            continue;
        }
        l.push(format!(
            "    pub async fn {}(&self{args}) -> Result<{}, CallError<{}>> {{",
            f.ident, f.ret, f.err_ty
        ));
        let call = match f.timeout_ms {
            Some(ms) => format!(
                "self.0.call_with_timeout(Self::PROTOCOL, {addr}, {param_expr}, core::time::Duration::from_millis({ms}))"
            ),
            None => format!("self.0.call(Self::PROTOCOL, {addr}, {param_expr})"),
        };
        l.push(format!("        let reply = {call}.await?;"));
        l.push("        let fmt = self.0.format();".into());
        l.push("        match reply.envelope() {".into());
        l.push("            Envelope::Ok(payload) => fmt.decode(payload).map_err(CallError::Runtime),".into());
        for (ord, err) in &f.throws {
            l.push(format!("            Envelope::Err {{ id: {ord}u16, body }} => {{"));
            l.push(format!("                let e: {err} = fmt.decode(body)?;"));
            l.push(format!("                Err(CallError::App({}::{err}(e)))", f.err_ty));
            l.push("            }".into());
        }
        l.push("            Envelope::Err { id, .. } => Err(CallError::Runtime(RuntimeError::Remote { id })),".into());
        l.push("            Envelope::Fault => Err(CallError::Runtime(RuntimeError::Provider)),".into());
        l.push("        }".into());
        l.push("    }".into());
    }
    l.push("}".into());
    l.push(String::new());
    l.push(String::new());
    l.join("\n")
}

/// The body of a dispatcher's `match` on the call: decode the params with
/// `fmt` (an expression: `fmt`, or `peer.format()` on a connection), run the
/// handler (given `peer` first when `peer` names it), and record the
/// outcome. Ends with the `match`'s closing brace.
///
/// `asynchronous`: the handler is awaited, and the outcome is the arm's
/// `Answer` rather than written into `reply`.
fn dispatch_arms(
    fns: &[FnInfo],
    param_members: &[Vec<Member>],
    calls_const: &str,
    fmt: &str,
    peer: &str,
    on_decode: ValidateOnDecode,
    asynchronous: bool,
) -> Vec<String> {
    let mut l: Vec<String> = Vec::new();
    l.push(format!(
        "        match call.resolve({calls_const}).ok_or(RuntimeError::UnknownCall)? {{"
    ));
    for (i, f) in fns.iter().enumerate() {
        l.push(format!("            {i} => {{"));
        // Params that will not decode are this call's failure, not the
        // connection's. A request/response call answers with a fault; a
        // one-way call has no response frame, so there is nowhere to say so
        // and it stops here. Doing this in the dispatcher rather than
        // leaving it to `Server` is what makes the call's arity count: the
        // server cannot see it.
        let on_undecodable: Vec<String> = match (f.one_way, asynchronous) {
            (true, false) => vec!["                    Err(_) => return Ok(()),".into()],
            (true, true) => vec!["                    Err(_) => return Ok(Answer::none()),".into()],
            (false, false) => vec![
                "                    Err(_) => {".into(),
                "                        reply.fault();".into(),
                "                        return Ok(());".into(),
                "                    }".into(),
            ],
            (false, true) => vec!["                    Err(_) => return Ok(Answer::fault()),".into()],
        };
        let call_args = match &f.params_ty {
            Some(ty) => {
                l.push(format!(
                    "                let p: {ty} = match {fmt}.decode(params) {{"
                ));
                l.push("                    Ok(p) => p,".into());
                l.extend(on_undecodable);
                l.push("                };".into());
                // Params that decode but fail their checks stop the same way.
                if on_decode != ValidateOnDecode::Off && validate::any_checks(&param_members[i]) {
                    let stop: &[&str] = match (f.one_way, asynchronous) {
                        (true, false) => &["return Ok(());"],
                        (true, true) => &["return Ok(Answer::none());"],
                        (false, false) => &["reply.fault();", "return Ok(());"],
                        (false, true) => &["return Ok(Answer::fault());"],
                    };
                    l.extend(validate::params_check(stop));
                }
                f.args
                    .iter()
                    .map(|a| format!("p.{}", a.ident))
                    .collect::<Vec<_>>()
                    .join(", ")
            }
            None => {
                l.push(format!("                let _: () = match {fmt}.decode(params) {{"));
                l.push("                    Ok(unit) => unit,".into());
                l.extend(on_undecodable);
                l.push("                };".into());
                String::new()
            }
        };
        let call_args = match (peer.is_empty(), call_args.is_empty()) {
            (true, _) => call_args,
            (false, true) => peer.to_string(),
            (false, false) => format!("{peer}, {call_args}"),
        };
        let call = format!("self.0.{}({call_args}){}", f.ident, if asynchronous { ".await" } else { "" });
        if asynchronous {
            if f.one_way {
                l.push(format!("                {call};"));
                l.push("                Ok(Answer::none())".into());
            } else {
                l.push(format!("                match {call} {{"));
                l.push("                    Ok(value) => {".into());
                l.push("                        let mut body = Vec::new();".into());
                l.push(format!("                        {fmt}.encode(&value, &mut body)?;"));
                l.push("                        Ok(Answer::ok(body))".into());
                l.push("                    }".into());
                for (ord, err) in &f.throws {
                    l.push(format!("                    Err(Fault::App({}::{err}(e))) => {{", f.err_ty));
                    l.push("                        let mut body = Vec::new();".into());
                    l.push(format!("                        {fmt}.encode(&e, &mut body)?;"));
                    l.push(format!("                        Ok(Answer::err({ord}u16, body))"));
                    l.push("                    }".into());
                }
                if f.throws.is_empty() {
                    l.push("                    Err(Fault::App(never)) => match never {},".into());
                }
                l.push("                    Err(Fault::Internal) => Ok(Answer::fault()),".into());
                l.push("                }".into());
            }
            l.push("            }".into());
            continue;
        }
        if f.one_way {
            // Run the handler; record nothing — the `Server` sees `Outcome::None`
            // and replies with nothing.
            l.push(format!("                {call};"));
        } else {
            l.push(format!("                match {call} {{"));
            l.push("                    Ok(value) => {".into());
            l.push("                        let mut body = Vec::new();".into());
            l.push(format!("                        {fmt}.encode(&value, &mut body)?;"));
            l.push("                        reply.ok(&body);".into());
            l.push("                    }".into());
            for (ord, err) in &f.throws {
                l.push(format!(
                    "                    Err(Fault::App({}::{err}(e))) => {{",
                    f.err_ty
                ));
                l.push("                        let mut body = Vec::new();".into());
                l.push(format!("                        {fmt}.encode(&e, &mut body)?;"));
                l.push(format!(
                    "                        reply.err({ord}u16, &body);"
                ));
                l.push("                    }".into());
            }
            if f.throws.is_empty() {
                // The error type is `Infallible`, so this arm is unreachable -
                // it is what keeps the `match` exhaustive.
                l.push("                    Err(Fault::App(never)) => match never {},".into());
            }
            l.push("                    Err(Fault::Internal) => reply.fault(),".into());
            l.push("                }".into());
        }
        l.push("                Ok(())".into());
        l.push("            }".into());
    }
    l.push("            _ => Err(RuntimeError::UnknownCall),".into());
    l.push("        }".into());
    l
}

// `errors` and `imports` are two unrelated lookup tables (ordinal → error
// type name; bare name → origin namespace) - bundling them into one
// context struct just to dodge this lint would force every caller of
// `rust_type`/`arg_types` to carry an `errors` table they never use.
#[allow(clippy::too_many_arguments)]
fn fn_info(
    proto: &str,
    name: &str,
    parameters: &[FrozenUnit],
    arguments: &[FrozenArgument],
    ret: &Option<TypeRef>,
    throws: &[u16],
    errors: &HashMap<u16, String>,
    imports: &HashMap<String, String>,
) -> FnInfo {
    let pascal_fn = pascal(name);
    let timeout_ms = annotation(parameters, "timeout_ms").and_then(|v| v.parse::<u64>().ok());
    let args: Vec<Arg> = arguments
        .iter()
        .map(|a| {
            let (sig_ty, field_ty) = arg_types(&a.ty, imports);
            Arg {
                name: a.name.clone(),
                ident: ident(&a.name),
                sig_ty,
                field_ty,
            }
        })
        .collect();
    let params_borrows = args.iter().any(Arg::borrows);
    let params_ty = if args.is_empty() {
        None
    } else {
        Some(format!("{proto}{pascal_fn}Params"))
    };
    let one_way = ret.is_none();
    let ret = match ret {
        None | Some(TypeRef::Unit) => "()".to_string(),
        Some(ty) => rust_type(ty, imports),
    };
    // A one-way function carries no `!` (nowhere to deliver it); ignore any.
    let throws: &[u16] = if one_way { &[] } else { throws };
    let throws: Vec<(u16, String)> = throws
        .iter()
        .map(|ord| {
            (
                *ord,
                errors
                    .get(ord)
                    .cloned()
                    .unwrap_or_else(|| format!("UnknownError{ord}")),
            )
        })
        .collect();
    FnInfo {
        method: name.to_string(),
        ident: ident(name),
        params_ty,
        params_borrows,
        args,
        ret,
        err_ty: format!("{proto}{pascal_fn}Error"),
        throws,
        one_way,
        timeout_ms,
    }
}

/// The text of a scalar `@key = value` annotation (frozen as
/// `FrozenUnit::Property`), by key.
///
/// The frozen value is typed now, so this renders it back to text for the
/// callers that only interpolate it. A caller that cares *which kind* of
/// value it got should match `ConfigValue` instead.
fn annotation<'a>(parameters: &'a [FrozenUnit], key: &str) -> Option<Cow<'a, str>> {
    parameters.iter().find_map(|p| match p {
        FrozenUnit::Property { name, value } if name == key => value.as_text(),
        _ => None,
    })
}

/// `(signature type, params-struct field type)` for a function argument.
/// A `str` / `string` arg is passed by reference and decoded borrowed from
/// the receive buffer; everything else is owned (borrowed arrays / nested
/// borrowed structs are a follow-up).
fn arg_types(ty: &TypeRef, imports: &HashMap<String, String>) -> (String, String) {
    match ty {
        TypeRef::Primitive(PrimitiveType::String) => ("&str".to_string(), "&'a str".to_string()),
        _ => {
            let owned = rust_type(ty, imports);
            (owned.clone(), owned)
        }
    }
}

